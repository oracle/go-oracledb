// decodeUniversalAt decodes a UNIVERSAL-encoded integer starting at idx.
// Returns (value, totalBytesConsumed, ok).
func decodeUniversalAt(b []byte, idx int) (int, int, bool) {
	if idx >= len(b) {
		return 0, 0, false
	}
	n := int(b[idx] & 0x7F)
	if n == 0 {
		return 0, 1, true // zero encoded as single 0x00
	}
	if idx+1+n > len(b) {
		return 0, 0, false
	}
	val := 0
	for i := 0; i < n; i++ {
		val = (val << 8) | int(b[idx+1+i])
	}
	return val, 1 + n, true
}

// maskValueAfterKey finds AUTH key occurrences and zeroes the following CLR payload
// (leaves UNIVERSAL length and CLR length untouched) to keep structure identical.
func maskValueAfterKey(buf []byte, key string) {
	keyBytes := []byte(key)
	for i := 0; i < len(buf); i++ {
		// Look for the key occurrence
		if i+len(keyBytes) <= len(buf) && bytes.Equal(buf[i:i+len(keyBytes)], keyBytes) {
			pos := i + len(keyBytes)
			// Next is UNIVERSAL UB4 value-length
			valLen, consumed, ok := decodeUniversalAt(buf, pos)
			_ = valLen // informational; CLR length below is authoritative
			if !ok {
				continue
			}
			// After UB4, next is CLR first length byte (short form assumed by golden)
			clrLenIdx := pos + consumed
			if clrLenIdx >= len(buf) {
				continue
			}
			clrLen := int(buf[clrLenIdx])
			dataStart := clrLenIdx + 1
			dataEnd := dataStart + clrLen
			if dataEnd <= len(buf) {
				// Zero only the value bytes
				for j := dataStart; j < dataEnd; j++ {
					buf[j] = 0
				}
			}
			// Continue search after this key to handle any future occurrences
			i = dataEnd - 1
		}
	}
}

// sanitizeOAuthDynamicValues returns a copy of pkt with dynamic credential values masked.
func sanitizeOAuthDynamicValues(pkt []byte) []byte {
	out := make([]byte, len(pkt))
	copy(out, pkt)
	maskValueAfterKey(out, authPassword)
	maskValueAfterKey(out, authPbkdf2SpeedyKey)
	maskValueAfterKey(out, authSesskey)
	maskValueAfterKey(out, authAlterSession)
	return out
}

// overwriteValueAfterKey writes value bytes over the CLR payload for the given key,
// without changing the encoded lengths. The number of bytes written is min(len(value), clrLen).
func overwriteValueAfterKey(buf []byte, key string, value []byte) {
	keyBytes := []byte(key)
	for i := 0; i+len(keyBytes) <= len(buf); i++ {
		if bytes.Equal(buf[i:i+len(keyBytes)], keyBytes) {
			pos := i + len(keyBytes)
			_, consumed, ok := decodeUniversalAt(buf, pos)
			if !ok {
				return
			}
			clrLenIdx := pos + consumed
			if clrLenIdx >= len(buf) {
				return
			}
			clrLen := int(buf[clrLenIdx])
			dataStart := clrLenIdx + 3
			dataEnd := dataStart + clrLen
			if dataEnd > len(buf) {
				return
			}
			n := len(value)
			if n > clrLen {
				n = clrLen
			}
			copy(buf[dataStart:dataStart+n], value[:n])
			return
		}
	}
}
