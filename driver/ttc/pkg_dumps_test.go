// ExtractBytesFromDump extracts the []byte from the dump
// for testing.
func ExtractBytesFromDump(lines []string) ([]byte, error) {
	buf := []byte{}
	isHex := regexp.MustCompile(`^[0-9A-Fa-f]{2}$`)

	for _, line := range lines {

		// Only take tokens that are exactly two hex chars; ignore ASCII preview.
		segment := line
		if start := strings.Index(segment, `"`); start >= 0 {
			if end := strings.LastIndex(segment, `"`); end > start {
				segment = segment[start+1 : end]
			}
		}
		for _, tok := range strings.Fields(segment) {
			if isHex.MatchString(tok) {
				b, _ := hex.DecodeString(tok)
				buf = append(buf, b...)
			}
		}
	}
	return buf, nil
}

